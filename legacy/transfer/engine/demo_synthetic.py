#!/usr/bin/env python3
"""Exercise the complete CLI using artificial cells only."""
import argparse
from fractions import Fraction as F
import json
from pathlib import Path
import subprocess
import sys

import holdout_engine as h


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--protocol", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    h.checked_protocol(args.protocol)
    if args.output.exists():
        parser.error("Choose a new synthetic output directory")
    args.output.mkdir(parents=True)
    names = ("India", "India_Wave2_New", "Kenya", "Brazil", "Excluded_fixture")
    data = {s: tuple(h.Cell(100, (42, 31, 25, 17, 8)[i]+j, F(100),
                            F((42, 31, 25, 17, 8)[i]+j))
                     for i in range(5)) for j, s in enumerate(names)}
    countries = {s: "India" if s.startswith("India") else s for s in names}
    for label, sources in (("training", names[:-1]), ("target", names[-1:])):
        payload = h.serialise_cells({s: data[s] for s in sources})
        (args.output/f"{label}.csv").write_bytes(payload)
        h.write_json(args.output/f"{label}_manifest.json", {
            "input_sha256": h.digest(payload), "evidence_type": "synthetic",
            "sources": {s: countries[s] for s in sources},
            "provenance": "Artificial integer-weight cells generated by demo_synthetic.py",
            "prior_exposure": "Synthetic fixture, no empirical inference"})
    commands = [
        ("fit", "training", "training_lock.json", []),
        ("score", "target", "target_scores.json", ["--lock", str(args.output/"training_lock.json"), "--country-disjoint"]),
        ("crossvalidate", "training", "source_cv.json", ["--unit", "source"]),
        ("crossvalidate", "training", "country_cv.json", ["--unit", "country"]),
    ]
    logs = []
    for command, label, name, options in commands:
        invocation = [sys.executable, str(Path(h.__file__)), command,
                      "--input", str(args.output/f"{label}.csv"),
                      "--manifest", str(args.output/f"{label}_manifest.json"),
                      "--protocol", str(args.protocol), "--output", str(args.output/name), *options]
        result = subprocess.run(invocation, text=True, capture_output=True)
        if result.returncode:
            raise RuntimeError(result.stderr)
        logs.append(json.loads(result.stdout))
    h.write_json(args.output/"SYNTHETIC_EXECUTION.json", {
        "status": "SYNTHETIC_CLI_PASS_NOT_EMPIRICAL", "engine_sha256": h.code_hash(),
        "protocol_sha256": h.checked_protocol(args.protocol), "commands": logs})
    print(json.dumps({"status": "SYNTHETIC_CLI_PASS_NOT_EMPIRICAL", "commands": len(logs)}))


if __name__ == "__main__":
    main()
